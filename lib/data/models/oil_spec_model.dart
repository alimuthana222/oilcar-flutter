import '../../domain/entities/oil_specification.dart';

class OilSpecModel extends OilSpecification {
  const OilSpecModel({
    required super.id,
    required super.brand,
    required super.model,
    required super.yearFrom,
    required super.yearTo,
    required super.engineType,
    super.engineDisplacement,
    required super.oilType,
    super.oilBrandRecommendation,
    required super.oilCapacityWithFilter,
    required super.oilCapacityWithoutFilter,
    super.oilCapacityUnit = 'liter',
    super.filterType,
    super.drainPlugTorque,
    super.oilChangeIntervalKm,
    super.oilChangeIntervalMonths,
    super.isSynthetic = true,
    super.viscosityGrade,
    super.apiCertification,
    super.specialNotes,
    super.sourceType = 'manual',
    super.isGulfMarket = false,
    required super.createdAt,
    required super.updatedAt,
  });
  
  factory OilSpecModel.fromJson(Map<String, dynamic> json) {
    return OilSpecModel(
      id: json['id'] as String,
      brand: json['brand'] as String,
      model: json['model'] as String,
      yearFrom: json['year_from'] as int,
      yearTo: json['year_to'] as int,
      engineType: json['engine_type'] as String,
      engineDisplacement: json['engine_displacement'] as String?,
      oilType: json['oil_type'] as String,
      oilBrandRecommendation: json['oil_brand_recommendation'] as String?,
      oilCapacityWithFilter: (json['oil_capacity_with_filter'] as num).toDouble(),
      oilCapacityWithoutFilter: (json['oil_capacity_without_filter'] as num).toDouble(),
      oilCapacityUnit: json['oil_capacity_unit'] as String? ?? 'liter',
      filterType: json['filter_type'] as String?,
      drainPlugTorque: json['drain_plug_torque'] as String?,
      oilChangeIntervalKm: json['oil_change_interval_km'] as int?,
      oilChangeIntervalMonths: json['oil_change_interval_months'] as int?,
      isSynthetic: json['is_synthetic'] as bool? ?? true,
      viscosityGrade: json['viscosity_grade'] as String?,
      apiCertification: json['api_certification'] as String?,
      specialNotes: json['special_notes'] as String?,
      sourceType: json['source_type'] as String? ?? 'manual',
      isGulfMarket: json['is_gulf_market'] as bool? ?? false,
      createdAt: DateTime.parse(json['created_at'] as String),
      updatedAt: DateTime.parse(json['updated_at'] as String),
    );
  }
  
  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'brand': brand,
      'model': model,
      'year_from': yearFrom,
      'year_to': yearTo,
      'engine_type': engineType,
      'engine_displacement': engineDisplacement,
      'oil_type': oilType,
      'oil_brand_recommendation': oilBrandRecommendation,
      'oil_capacity_with_filter': oilCapacityWithFilter,
      'oil_capacity_without_filter': oilCapacityWithoutFilter,
      'oil_capacity_unit': oilCapacityUnit,
      'filter_type': filterType,
      'drain_plug_torque': drainPlugTorque,
      'oil_change_interval_km': oilChangeIntervalKm,
      'oil_change_interval_months': oilChangeIntervalMonths,
      'is_synthetic': isSynthetic,
      'viscosity_grade': viscosityGrade,
      'api_certification': apiCertification,
      'special_notes': specialNotes,
      'source_type': sourceType,
      'is_gulf_market': isGulfMarket,
      'created_at': createdAt.toIso8601String(),
      'updated_at': updatedAt.toIso8601String(),
    };
  }
  
  OilSpecification toEntity() {
    return OilSpecification(
      id: id,
      brand: brand,
      model: model,
      yearFrom: yearFrom,
      yearTo: yearTo,
      engineType: engineType,
      engineDisplacement: engineDisplacement,
      oilType: oilType,
      oilBrandRecommendation: oilBrandRecommendation,
      oilCapacityWithFilter: oilCapacityWithFilter,
      oilCapacityWithoutFilter: oilCapacityWithoutFilter,
      oilCapacityUnit: oilCapacityUnit,
      filterType: filterType,
      drainPlugTorque: drainPlugTorque,
      oilChangeIntervalKm: oilChangeIntervalKm,
      oilChangeIntervalMonths: oilChangeIntervalMonths,
      isSynthetic: isSynthetic,
      viscosityGrade: viscosityGrade,
      apiCertification: apiCertification,
      specialNotes: specialNotes,
      sourceType: sourceType,
      isGulfMarket: isGulfMarket,
      createdAt: createdAt,
      updatedAt: updatedAt,
    );
  }
  
  factory OilSpecModel.fromEntity(OilSpecification entity) {
    return OilSpecModel(
      id: entity.id,
      brand: entity.brand,
      model: entity.model,
      yearFrom: entity.yearFrom,
      yearTo: entity.yearTo,
      engineType: entity.engineType,
      engineDisplacement: entity.engineDisplacement,
      oilType: entity.oilType,
      oilBrandRecommendation: entity.oilBrandRecommendation,
      oilCapacityWithFilter: entity.oilCapacityWithFilter,
      oilCapacityWithoutFilter: entity.oilCapacityWithoutFilter,
      oilCapacityUnit: entity.oilCapacityUnit,
      filterType: entity.filterType,
      drainPlugTorque: entity.drainPlugTorque,
      oilChangeIntervalKm: entity.oilChangeIntervalKm,
      oilChangeIntervalMonths: entity.oilChangeIntervalMonths,
      isSynthetic: entity.isSynthetic,
      viscosityGrade: entity.viscosityGrade,
      apiCertification: entity.apiCertification,
      specialNotes: entity.specialNotes,
      sourceType: entity.sourceType,
      isGulfMarket: entity.isGulfMarket,
      createdAt: entity.createdAt,
      updatedAt: entity.updatedAt,
    );
  }
}